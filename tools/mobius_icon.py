#!/usr/bin/env python3
import math, sys
# Makes the Mobius logo drawables (D-050): python3 tools/mobius_icon.py app/src/main/res/drawable
COLORS=[0x5BD8E6,0x6A8DFF,0xA35BFF,0xFF5BC8,0xA35BFF,0x6A8DFF]
def blend(t):
    f=(t%1)*len(COLORS); i=int(f)%len(COLORS); j=(i+1)%len(COLORS); k=f-int(f)
    a,b=COLORS[i],COLORS[j]
    return [ (a>>s&255)+((b>>s&255)-(a>>s&255))*k for s in (16,8,0)]
def faces(seg, spin=2.8, tilt=0.9, sway=0.0, hw=0.3):
    cs,ss,ct,st,cw,sw=math.cos(spin),math.sin(spin),math.cos(tilt),math.sin(tilt),math.cos(sway),math.sin(sway)
    def pt(u,v):
        r=1+v*hw*math.cos(u/2); return (r*math.cos(u), r*math.sin(u), v*hw*math.sin(u/2))
    def pr(p):
        x1=p[0]*cs-p[1]*ss; y1=p[0]*ss+p[1]*cs; z1=p[2]
        y2=y1*ct-z1*st; z2=y1*st+z1*ct
        x3=x1*cw+z2*sw; z3=-x1*sw+z2*cw
        k=3.2/(3.2-z3); return (x3*k,y2*k,z3)
    L=(-0.35,-0.55,0.76)
    out=[]
    for i in range(seg):
        u0=2*math.pi*i/seg; u1=2*math.pi*(i+1)/seg
        a,b,c,d=pr(pt(u0,-1)),pr(pt(u0,1)),pr(pt(u1,1)),pr(pt(u1,-1))
        e1=[c[j]-a[j] for j in range(3)]; e2=[b[j]-d[j] for j in range(3)]
        n=[e1[1]*e2[2]-e1[2]*e2[1], e1[2]*e2[0]-e1[0]*e2[2], e1[0]*e2[1]-e1[1]*e2[0]]
        l=math.sqrt(sum(x*x for x in n)) or 1
        back=(c[0]-a[0])*(b[1]-d[1])-(c[1]-a[1])*(b[0]-d[0])<0
        lit=(0.4+0.6*abs(sum(n[j]/l*L[j] for j in range(3))))*(0.7 if back else 1)
        out.append(((a[2]+b[2]+c[2]+d[2])/4, lit, (i+.5)/seg, [a,b,c,d]))
    out.sort(key=lambda f:f[0]); return out
def vector(size, view, cx, cy, unit, mode):
    fs=faces(96)
    lines=['<?xml version="1.0" encoding="utf-8"?>',
      '<!-- Jimi logo: Möbius strip (D-050). Generated by tools/mobius_icon.py (same math as MobiusMath.kt); do not edit by hand. -->',
      f'<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="{size}dp" android:height="{size}dp" android:viewportWidth="{view}" android:viewportHeight="{view}">']
    for depth,lit,along,pts in fs:
        near=min(1,max(0,(depth+0.6)/1.2))
        d="M"+" L".join(f"{cx+p[0]*unit:.2f},{cy+p[1]*unit:.2f}" for p in pts)+"Z"
        if mode=="color":
            r,g,b=[min(255,int(c*lit)) for c in blend(along)]
            col=f"#FF{r:02X}{g:02X}{b:02X}"
            lines.append(f'  <path android:fillColor="{col}" android:strokeColor="{col}" android:strokeWidth="0.25" android:pathData="{d}"/>')
            rr,rg,rb=[min(255,int(x+(255-x)*0.35)) for x in (r,g,b)]
            P=[f"{cx+p[0]*unit:.2f},{cy+p[1]*unit:.2f}" for p in pts]
            lines.append(f'  <path android:strokeColor="#FF{rr:02X}{rg:02X}{rb:02X}" android:strokeWidth="0.5" android:pathData="M{P[1]} L{P[2]} M{P[0]} L{P[3]}"/>')
        elif mode=="solid":
            lines.append(f'  <path android:fillColor="#FFFFFFFF" android:strokeColor="#FFFFFFFF" android:strokeWidth="0.1" android:pathData="{d}"/>')
        else:
            a=0.45+0.55*lit*near
            lines.append(f'  <path android:fillColor="#FFFFFFFF" android:fillAlpha="{a:.2f}" android:pathData="{d}"/>')
    lines.append('</vector>')
    return "\n".join(lines)+"\n"
import os
res=sys.argv[1]
open(os.path.join(res,"ic_launcher_foreground.xml"),"w").write(vector(108,108,54,54,30/1.3,"color"))
open(os.path.join(res,"ic_launcher_monochrome.xml"),"w").write(vector(108,108,54,54,30/1.3,"solid"))
open(os.path.join(res,"ic_jarvis.xml"),"w").write(vector(24,24,12,12,11/1.4,"solid"))
